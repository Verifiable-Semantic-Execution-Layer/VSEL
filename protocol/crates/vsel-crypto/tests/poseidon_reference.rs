// ============================================================================
// Task 3.2: MDS Matrix Non-Singularity Verification (Requirement 3.4)
// ============================================================================
//
// The MDS property requires that every square submatrix of the 12×12 Cauchy
// matrix is non-singular over the Goldilocks field. We verify this by:
// 1. Constructing the MDS matrix with x_i = i+1, y_j = 12+j+1
// 2. Enumerating all square submatrices for sizes 1 through 12
// 3. Computing determinants over the Goldilocks field
// 4. Asserting all determinants are non-zero
//
// Total submatrices: sum_{k=1}^{12} C(12,k)^2 = 4,083,150 + 1 (full matrix)
// This is computationally feasible as a one-time test.

/// Generate the 12×12 Cauchy MDS matrix with x_i = i+1, y_j = 12+j+1.
fn generate_mds_matrix() -> [[GoldilocksField; 12]; 12] {
    let mut matrix = [[GoldilocksField::ZERO; 12]; 12];
    for i in 0..12 {
        for j in 0..12 {
            let x_i = GoldilocksField((i + 1) as u64);
            let y_j = GoldilocksField((12 + j + 1) as u64);
            let sum = x_i.add(y_j);
            matrix[i][j] = sum.inv().expect("MDS Cauchy matrix: sum must be non-zero");
        }
    }
    matrix
}

/// Compute the determinant of a square matrix over GoldilocksField using
/// Gaussian elimination with partial pivoting.
fn determinant(matrix: &[Vec<GoldilocksField>]) -> GoldilocksField {
    let n = matrix.len();
    if n == 0 {
        return GoldilocksField::ONE;
    }
    if n == 1 {
        return matrix[0][0];
    }

    // Work on a mutable copy
    let mut m: Vec<Vec<GoldilocksField>> = matrix.to_vec();
    let mut det = GoldilocksField::ONE;

    for col in 0..n {
        // Find pivot (first non-zero in column)
        let mut pivot_row = None;
        for row in col..n {
            if m[row][col] != GoldilocksField::ZERO {
                pivot_row = Some(row);
                break;
            }
        }

        let pivot_row = match pivot_row {
            Some(r) => r,
            None => return GoldilocksField::ZERO, // Singular
        };

        // Swap rows if needed
        if pivot_row != col {
            m.swap(col, pivot_row);
            // Swapping rows negates the determinant: multiply by (p-1) = -1
            det = det.mul(GoldilocksField(GoldilocksField::MODULUS - 1));
        }

        let pivot = m[col][col];
        det = det.mul(pivot);

        // Eliminate below
        let pivot_inv = pivot.inv().expect("pivot is non-zero");
        for row in (col + 1)..n {
            let factor = m[row][col].mul(pivot_inv);
            m[row][col] = GoldilocksField::ZERO;
            for j in (col + 1)..n {
                let sub_val = factor.mul(m[col][j]);
                m[row][j] = m[row][j].sub(sub_val);
            }
        }
    }

    det
}

/// Extract a submatrix given row and column index sets.
fn extract_submatrix(
    matrix: &[[GoldilocksField; 12]; 12],
    rows: &[usize],
    cols: &[usize],
) -> Vec<Vec<GoldilocksField>> {
    rows.iter()
        .map(|&r| cols.iter().map(|&c| matrix[r][c]).collect())
        .collect()
}

/// Generate all combinations of `k` elements from `0..n`.
fn combinations(n: usize, k: usize) -> Vec<Vec<usize>> {
    let mut result = Vec::new();
    let mut combo = vec![0usize; k];

    fn generate(combo: &mut Vec<usize>, start: usize, n: usize, k: usize, pos: usize, result: &mut Vec<Vec<usize>>) {
        if pos == k {
            result.push(combo.clone());
            return;
        }
        for i in start..=(n - k + pos) {
            combo[pos] = i;
            generate(combo, i + 1, n, k, pos + 1, result);
        }
    }

    generate(&mut combo, 0, n, k, 0, &mut result);
    result
}

/// Verify that every square submatrix of the 12×12 Cauchy MDS matrix is
/// non-singular over the Goldilocks field.
///
/// This is the definitive MDS property check: a matrix is MDS if and only if
/// every square submatrix has non-zero determinant.
///
/// Requirements: 3.4
#[test]
fn test_mds_matrix_all_square_submatrices_nonsingular() {
    let mds = generate_mds_matrix();
    let mut total_checked = 0u64;
    let mut singular_found = Vec::new();

    for k in 1..=12usize {
        let row_combos = combinations(12, k);
        let col_combos = combinations(12, k);

        for rows in &row_combos {
            for cols in &col_combos {
                let sub = extract_submatrix(&mds, rows, cols);
                let det = determinant(&sub);
                total_checked += 1;

                if det == GoldilocksField::ZERO {
                    singular_found.push((k, rows.clone(), cols.clone()));
                }
            }
        }
    }

    assert!(
        singular_found.is_empty(),
        "MDS property VIOLATED: found {} singular submatrices out of {} checked.\n\
         First singular submatrix: size={}, rows={:?}, cols={:?}",
        singular_found.len(),
        total_checked,
        singular_found[0].0,
        singular_found[0].1,
        singular_found[0].2,
    );

    // Verify we checked the expected number of submatrices
    // sum_{k=1}^{12} C(12,k)^2
    let expected_count: u64 = (1..=12u64)
        .map(|k| {
            let c = combinations(12, k as usize).len() as u64;
            c * c
        })
        .sum();
    assert_eq!(
        total_checked, expected_count,
        "Expected to check {} submatrices, checked {}",
        expected_count, total_checked
    );

    println!(
        "MDS property verified: all {} square submatrices are non-singular",
        total_checked
    );
}

/// Verify the full 12×12 MDS matrix determinant is non-zero.
#[test]
fn test_mds_full_matrix_nonsingular() {
    let mds = generate_mds_matrix();
    let full: Vec<Vec<GoldilocksField>> = (0..12)
        .map(|i| mds[i].to_vec())
        .collect();
    let det = determinant(&full);
    assert_ne!(
        det,
        GoldilocksField::ZERO,
        "Full 12×12 MDS matrix must be non-singular"
    );
}

/// Verify MDS matrix entries match the Cauchy construction formula.
#[test]
fn test_mds_matrix_cauchy_construction() {
    let mds = generate_mds_matrix();
    for i in 0..12 {
        for j in 0..12 {
            let x_i = GoldilocksField((i + 1) as u64);
            let y_j = GoldilocksField((12 + j + 1) as u64);
            let expected = x_i.add(y_j).inv().unwrap();
            assert_eq!(
                mds[i][j], expected,
                "MDS[{}][{}] does not match Cauchy formula 1/(x_i + y_j)",
                i, j
            );
        }
    }
}

