// ============================================================================
// Task 3.3: Conformance Tests Against Reference Vectors (Requirement 3.5)
// ============================================================================
//
// These tests compare PoseidonGoldilocks::permute() output against every
// hardcoded reference test vector. They fail the build if any vector diverges.

#[test]
fn test_conformance_all_reference_vectors() {
    let poseidon = PoseidonGoldilocks::new();
    let vectors = reference_vectors();

    assert!(
        vectors.len() >= 20,
        "Must have at least 20 reference vectors, got {}",
        vectors.len()
    );

    for (name, input, expected) in &vectors {
        let mut state = state_from(input);
        poseidon.permute(&mut state);
        let actual = state_to_u64(&state);

        assert_eq!(
            &actual, expected,
            "Reference vector '{}' DIVERGED!\n  Input:    {:?}\n  Expected: {:?}\n  Actual:   {:?}",
            name, input, expected, actual
        );
    }
}

