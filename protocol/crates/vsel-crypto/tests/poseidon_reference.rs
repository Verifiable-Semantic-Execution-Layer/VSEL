use vsel_crypto::goldilocks::GoldilocksField;
use vsel_crypto::poseidon_goldilocks::{PoseidonGoldilocks, STATE_WIDTH};

// ============================================================================
// Helpers
// ============================================================================

/// Helper: create a state from a slice of u64 values.
fn state_from(vals: &[u64; STATE_WIDTH]) -> [GoldilocksField; STATE_WIDTH] {
    let mut state = [GoldilocksField::ZERO; STATE_WIDTH];
    for i in 0..STATE_WIDTH {
        state[i] = GoldilocksField(vals[i]);
    }
    state
}

/// Helper: extract u64 values from a state.
fn state_to_u64(state: &[GoldilocksField; STATE_WIDTH]) -> [u64; STATE_WIDTH] {
    let mut vals = [0u64; STATE_WIDTH];
    for i in 0..STATE_WIDTH {
        vals[i] = state[i].0;
    }
    vals
}

